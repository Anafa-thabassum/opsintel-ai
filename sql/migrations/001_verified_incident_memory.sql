-- Separate, additive Exasol memory schema. Never reset existing telemetry.
CREATE TABLE IF NOT EXISTS OPSINTEL.INCIDENT_SUBMISSIONS (
    SUBMISSION_ID VARCHAR(36) PRIMARY KEY,
    RUN_ID DECIMAL(18,0) NOT NULL,
    PIPELINE_NAME VARCHAR(100) NOT NULL,
    KIND VARCHAR(20) NOT NULL,
    SOURCE_INCIDENT_ID VARCHAR(36),
    CATEGORY VARCHAR(40) NOT NULL,
    CAUSE_DESCRIPTION VARCHAR(2000) NOT NULL,
    EVIDENCE_JSON VARCHAR(20000) NOT NULL,
    CLASSIFICATION_JSON VARCHAR(20000) NOT NULL,
    FINGERPRINT_JSON VARCHAR(20000) NOT NULL,
    SUBMITTED_BY VARCHAR(100) NOT NULL,
    SUBMITTED_AT TIMESTAMP NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    REVIEWED_BY VARCHAR(100),
    REVIEWED_AT TIMESTAMP,
    REVIEW_RATIONALE VARCHAR(2000),
    CHECKLIST_JSON VARCHAR(20000)
);

CREATE TABLE IF NOT EXISTS OPSINTEL.CONFIRMED_INCIDENTS (
    INCIDENT_ID VARCHAR(36) NOT NULL,
    RUN_ID DECIMAL(18,0) PRIMARY KEY,
    PIPELINE_NAME VARCHAR(100) NOT NULL,
    CONFIRMED_CATEGORY VARCHAR(40) NOT NULL,
    CONFIRMED_DESCRIPTION VARCHAR(2000) NOT NULL,
    FINGERPRINT_VERSION VARCHAR(40) NOT NULL,
    FINGERPRINT_JSON VARCHAR(20000) NOT NULL,
    EVIDENCE_JSON VARCHAR(20000) NOT NULL,
    CONFIRMED_BY VARCHAR(100) NOT NULL,
    CONFIRMED_AT TIMESTAMP NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    SOURCE_INCIDENT_ID VARCHAR(36),
    REVISION DECIMAL(18,0) NOT NULL
);

CREATE TABLE IF NOT EXISTS OPSINTEL.INCIDENT_FEATURES (
    INCIDENT_ID VARCHAR(36) NOT NULL,
    FEATURE_NAME VARCHAR(100) NOT NULL,
    FEATURE_VALUE VARCHAR(500) NOT NULL,
    FEATURE_TYPE VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS OPSINTEL.INCIDENT_MATCHES (
    MATCH_ID VARCHAR(36) PRIMARY KEY,
    SOURCE_RUN_ID DECIMAL(18,0) NOT NULL,
    MATCHED_INCIDENT_ID VARCHAR(36) NOT NULL,
    SIMILARITY_SCORE DECIMAL(6,4) NOT NULL,
    FINGERPRINT_VERSION VARCHAR(40) NOT NULL,
    MATCHING_FEATURES VARCHAR(4000) NOT NULL,
    DIFFERING_FEATURES VARCHAR(4000) NOT NULL,
    MATCH_STATUS VARCHAR(30) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    REVIEWED_BY VARCHAR(100),
    REVIEWED_AT TIMESTAMP
);

CREATE TABLE IF NOT EXISTS OPSINTEL.INCIDENT_AUDIT (
    AUDIT_ID VARCHAR(36) PRIMARY KEY,
    INCIDENT_ID VARCHAR(36),
    SUBMISSION_ID VARCHAR(36),
    RUN_ID DECIMAL(18,0) NOT NULL,
    AUDIT_ACTION VARCHAR(30) NOT NULL,
    ACTOR_ID VARCHAR(100) NOT NULL,
    RATIONALE VARCHAR(2000) NOT NULL,
    BEFORE_JSON VARCHAR(20000),
    AFTER_JSON VARCHAR(20000),
    CREATED_AT TIMESTAMP NOT NULL
);
