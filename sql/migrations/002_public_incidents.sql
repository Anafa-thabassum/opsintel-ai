-- Public issue metadata and short diagnostic excerpts. Raw issue bodies are not stored.
CREATE TABLE IF NOT EXISTS OPSINTEL.PUBLIC_INCIDENTS (
    SOURCE_KEY VARCHAR(120) PRIMARY KEY,
    SOURCE_NAME VARCHAR(80) NOT NULL,
    SOURCE_REPOSITORY VARCHAR(120) NOT NULL,
    ISSUE_NUMBER DECIMAL(18,0) NOT NULL,
    SOURCE_URL VARCHAR(1000) NOT NULL,
    TITLE VARCHAR(1000) NOT NULL,
    EXCERPT VARCHAR(2000) NOT NULL,
    EXCERPT_ORIGIN VARCHAR(80) NOT NULL,
    SOURCE_STATE VARCHAR(20) NOT NULL,
    SOURCE_CREATED_AT TIMESTAMP NOT NULL,
    SOURCE_UPDATED_AT TIMESTAMP NOT NULL,
    COLLECTED_AT TIMESTAMP NOT NULL,
    BODY_SHA256 VARCHAR(64) NOT NULL,
    PROJECT_LABEL VARCHAR(40),
    LABEL_STATUS VARCHAR(60) NOT NULL,
    CLASSIFIER_CATEGORY VARCHAR(40) NOT NULL,
    CLASSIFICATION_JSON VARCHAR(20000) NOT NULL,
    CODE_LICENSE VARCHAR(60) NOT NULL,
    CODE_LICENSE_URL VARCHAR(1000) NOT NULL,
    ISSUE_TEXT_LICENSE_STATUS VARCHAR(100) NOT NULL
);
