CREATE SCHEMA IF NOT EXISTS OPSINTEL;

CREATE TABLE OPSINTEL.ORDERS (
    ORDER_ID DECIMAL(18,0),
    REGION VARCHAR(50),
    AMOUNT DECIMAL(12,2),
    ORDER_DATE DATE
);

CREATE TABLE OPSINTEL.PIPELINE_RUNS (
    RUN_ID DECIMAL(18,0),
    PIPELINE_NAME VARCHAR(100),
    RUN_STATUS VARCHAR(20),
    EXPECTED_ROWS DECIMAL(18,0),
    ACTUAL_ROWS DECIMAL(18,0),
    RUN_TIME TIMESTAMP
);

CREATE TABLE OPSINTEL.INCIDENTS (
    INCIDENT_ID DECIMAL(18,0),
    INCIDENT_TYPE VARCHAR(100),
    SEVERITY VARCHAR(20),
    DESCRIPTION VARCHAR(500),
    STATUS VARCHAR(30),
    CREATED_AT TIMESTAMP
);

CREATE TABLE OPSINTEL.PIPELINE_LOGS (
    LOG_ID DECIMAL(18,0),
    RUN_ID DECIMAL(18,0),
    LOG_LEVEL VARCHAR(20),
    LOG_MESSAGE VARCHAR(500),
    LOG_TIME TIMESTAMP
);

CREATE TABLE OPSINTEL.PIPELINE_DEPENDENCIES (
    UPSTREAM_PIPELINE VARCHAR(100),
    DOWNSTREAM_PIPELINE VARCHAR(100)
);
