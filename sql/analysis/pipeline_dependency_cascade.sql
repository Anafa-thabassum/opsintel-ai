CREATE OR REPLACE VIEW OPSINTEL.PIPELINE_DEPENDENCY_CASCADE AS
SELECT
    CONNECT_BY_ROOT UPSTREAM_PIPELINE AS ROOT_PIPELINE,
    DOWNSTREAM_PIPELINE,
    LEVEL AS DEPENDENCY_DEPTH,
    SYS_CONNECT_BY_PATH(DOWNSTREAM_PIPELINE, ' -> ') AS DEPENDENCY_PATH
FROM OPSINTEL.PIPELINE_DEPENDENCIES
CONNECT BY NOCYCLE PRIOR DOWNSTREAM_PIPELINE = UPSTREAM_PIPELINE;
