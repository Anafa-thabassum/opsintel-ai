CREATE OR REPLACE VIEW OPSINTEL.PIPELINE_HEALTH_FEATURES AS
SELECT
    RUN_ID,
    PIPELINE_NAME,
    RUN_STATUS,
    EXPECTED_ROWS,
    ACTUAL_ROWS,
    RUN_TIME,
    CASE
        WHEN RUN_STATUS = 'FAILED' THEN 1
        WHEN EXPECTED_ROWS IS NOT NULL
         AND ACTUAL_ROWS IS NOT NULL
         AND EXPECTED_ROWS <> ACTUAL_ROWS THEN 1
        ELSE 0
    END AS IS_INCIDENT,
    CASE
        WHEN EXPECTED_ROWS IS NULL OR ACTUAL_ROWS IS NULL THEN NULL
        ELSE GREATEST(EXPECTED_ROWS - ACTUAL_ROWS, 0)
    END AS MISSING_ROWS,
    CASE
        WHEN EXPECTED_ROWS IS NULL OR ACTUAL_ROWS IS NULL THEN NULL
        ELSE GREATEST(ACTUAL_ROWS - EXPECTED_ROWS, 0)
    END AS EXCESS_ROWS,
    CASE
        WHEN EXPECTED_ROWS IS NULL OR ACTUAL_ROWS IS NULL THEN NULL
        WHEN EXPECTED_ROWS = 0 AND ACTUAL_ROWS = 0 THEN 100
        WHEN EXPECTED_ROWS = 0 THEN NULL
        ELSE ROUND(ACTUAL_ROWS * 100.0 / EXPECTED_ROWS, 2)
    END AS COMPLETENESS_PCT,
    LAG(RUN_STATUS) OVER (
        PARTITION BY PIPELINE_NAME
        ORDER BY RUN_TIME, RUN_ID
    ) AS PREVIOUS_STATUS,
    ROUND(AVG(ACTUAL_ROWS) OVER (
        PARTITION BY PIPELINE_NAME
        ORDER BY RUN_TIME, RUN_ID
        ROWS BETWEEN 4 PRECEDING AND CURRENT ROW
    ), 2) AS ROLLING_AVG_ACTUAL_ROWS,
    ROUND(
        SUM(CASE WHEN RUN_STATUS = 'FAILED' THEN 1 ELSE 0 END) OVER (
            PARTITION BY PIPELINE_NAME
            ORDER BY RUN_TIME, RUN_ID
            ROWS BETWEEN 4 PRECEDING AND CURRENT ROW
        ) * 100.0
        / COUNT(*) OVER (
            PARTITION BY PIPELINE_NAME
            ORDER BY RUN_TIME, RUN_ID
            ROWS BETWEEN 4 PRECEDING AND CURRENT ROW
        ),
        2
    ) AS ROLLING_FAILURE_RATE_PCT
FROM OPSINTEL.PIPELINE_RUNS;
