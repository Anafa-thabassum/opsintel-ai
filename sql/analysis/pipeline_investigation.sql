-- 1. Inspect all pipeline runs
SELECT
    RUN_ID,
    PIPELINE_NAME,
    RUN_STATUS,
    EXPECTED_ROWS,
    ACTUAL_ROWS
FROM OPSINTEL.PIPELINE_RUNS
ORDER BY RUN_ID;


-- 2. Find pipelines with missing rows
SELECT
    RUN_ID,
    PIPELINE_NAME,
    EXPECTED_ROWS,
    ACTUAL_ROWS,
    EXPECTED_ROWS - ACTUAL_ROWS AS MISSING_ROWS
FROM OPSINTEL.PIPELINE_RUNS
WHERE EXPECTED_ROWS > ACTUAL_ROWS
ORDER BY RUN_ID;


-- 3. Join failed pipelines with their logs
SELECT DISTINCT
    r.RUN_ID,
    r.PIPELINE_NAME,
    r.RUN_STATUS,
    l.LOG_ID,
    l.LOG_LEVEL,
    l.LOG_MESSAGE
FROM OPSINTEL.PIPELINE_RUNS r
JOIN OPSINTEL.PIPELINE_LOGS l
    ON r.RUN_ID = l.RUN_ID
WHERE r.RUN_STATUS = 'FAILED'
ORDER BY r.RUN_ID, l.LOG_ID;
