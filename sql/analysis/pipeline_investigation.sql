-- 1. Historical completeness and recent-run comparison
SELECT
    RUN_ID,
    PIPELINE_NAME,
    RUN_STATUS,
    EXPECTED_ROWS,
    ACTUAL_ROWS,
    MISSING_ROWS,
    COMPLETENESS_PCT,
    PREVIOUS_STATUS,
    ROLLING_AVG_ACTUAL_ROWS,
    ROLLING_FAILURE_RATE_PCT,
    RUN_TIME
FROM OPSINTEL.PIPELINE_HEALTH_FEATURES
WHERE PIPELINE_NAME = 'daily_sales_import'
ORDER BY RUN_TIME DESC, RUN_ID DESC;


-- 2. Current incidents and row-count discrepancies
SELECT
    RUN_ID,
    PIPELINE_NAME,
    EXPECTED_ROWS,
    ACTUAL_ROWS,
    EXPECTED_ROWS - ACTUAL_ROWS AS MISSING_ROWS
FROM OPSINTEL.PIPELINE_RUNS
WHERE EXPECTED_ROWS > ACTUAL_ROWS
ORDER BY RUN_ID;


-- 3. Evidence retrieval for the selected failed run
SELECT DISTINCT
    r.RUN_ID,
    r.PIPELINE_NAME,
    r.RUN_STATUS,
    r.EXPECTED_ROWS,
    r.ACTUAL_ROWS,
    r.EXPECTED_ROWS - r.ACTUAL_ROWS AS MISSING_ROWS,
    l.LOG_ID,
    l.LOG_LEVEL,
    l.LOG_MESSAGE,
    l.LOG_TIME
FROM OPSINTEL.PIPELINE_RUNS r
JOIN OPSINTEL.PIPELINE_LOGS l
    ON r.RUN_ID = l.RUN_ID
WHERE r.RUN_ID = 1
ORDER BY r.RUN_ID, l.LOG_ID;


-- 4. Cross-pipeline failure cascade from the latest failed runs
WITH LATEST_FAILED AS (
    SELECT
        RUN_ID,
        PIPELINE_NAME,
        RUN_STATUS,
        RUN_TIME,
        ROW_NUMBER() OVER (
            PARTITION BY PIPELINE_NAME
            ORDER BY RUN_TIME DESC, RUN_ID DESC
        ) AS RECENCY_RANK
    FROM OPSINTEL.PIPELINE_RUNS
    WHERE RUN_STATUS = 'FAILED'
)
SELECT
    cascade.ROOT_PIPELINE,
    upstream.RUN_ID AS ROOT_RUN_ID,
    cascade.DOWNSTREAM_PIPELINE,
    downstream.RUN_ID AS DOWNSTREAM_RUN_ID,
    cascade.DEPENDENCY_DEPTH,
    cascade.DEPENDENCY_PATH
FROM OPSINTEL.PIPELINE_DEPENDENCY_CASCADE cascade
JOIN LATEST_FAILED upstream
    ON upstream.PIPELINE_NAME = cascade.ROOT_PIPELINE
   AND upstream.RECENCY_RANK = 1
JOIN LATEST_FAILED downstream
    ON downstream.PIPELINE_NAME = cascade.DOWNSTREAM_PIPELINE
   AND downstream.RECENCY_RANK = 1
ORDER BY upstream.RUN_ID, cascade.DEPENDENCY_DEPTH, downstream.RUN_ID;
